    STANDARD_WEBSEITE("STANDARD_WEBSEITE"),
    TOP_3_KERNAUSSAGEN("TOP_3_KERNAUSSAGEN"),
    FACTS_VS_OPINIONS_ANALYZER("FACTS_VS_OPINIONS_ANALYZER"),
    PERSPECTIVES_AND_COUNTERPOSITIONS("PERSPECTIVES_AND_COUNTERPOSITIONS"),
    MULTIMEDIA("MULTIMEDIA"),
    FREIE_QUELLENANFRAGE("FREIE_QUELLENANFRAGE"),
    DOKUMENTE("DOKUMENTE"),
    AKTUALITAETS_CHECK("AKTUALITAETS_CHECK"),
    FEHLINFORMATIONS_RADAR("FEHLINFORMATIONS_RADAR"),
    RISIKO_ANALYSE("RISIKO_ANALYSE"),
    BUSINESS_INKUBATOR("BUSINESS_INKUBATOR"),
    WEITERE_RELEVANTE_ASPEKTE("WEITERE_RELEVANTE_ASPEKTE"),
    
    // New English/Canonical values
    WEB_SUMMARY("WEB_SUMMARY"),
    KEY_TAKEAWAYS("KEY_TAKEAWAYS"),
    RELEVANT_ASPECTS("RELEVANT_ASPECTS"),
    DOCUMENT_SUMMARY("DOCUMENT_SUMMARY"),
    FREE_SOURCE_QUERY("FREE_SOURCE_QUERY"),
    MULTIMEDIA_ANALYSIS("MULTIMEDIA_ANALYSIS"),
    FRESHNESS_CHECK("FRESHNESS_CHECK"),
    MISINFORMATION_RADAR("MISINFORMATION_RADAR"),
    FACTS_VS_OPINIONS("FACTS_VS_OPINIONS"),
    RISK_ANALYSIS("RISK_ANALYSIS"),
