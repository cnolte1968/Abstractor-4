    PHOTO_SCREENSHOT_ANALYSIS("PHOTO_SCREENSHOT_ANALYSIS");

    fun canonical(): AnalysisType = when (this) {
        STANDARD_WEBSEITE -> WEB_SUMMARY
        TOP_3_KERNAUSSAGEN -> KEY_TAKEAWAYS
        WEITERE_RELEVANTE_ASPEKTE -> RELEVANT_ASPECTS
        DOKUMENTE -> DOCUMENT_SUMMARY
        FREIE_QUELLENANFRAGE -> FREE_SOURCE_QUERY
        MULTIMEDIA -> MULTIMEDIA_ANALYSIS
        AKTUALITAETS_CHECK -> FRESHNESS_CHECK
        FEHLINFORMATIONS_RADAR -> MISINFORMATION_RADAR
        FACTS_VS_OPINIONS_ANALYZER -> FACTS_VS_OPINIONS
        RISIKO_ANALYSE -> RISK_ANALYSIS
